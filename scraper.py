import requests
import zipfile
import io
import pandas as pd
import datetime
from pathlib import Path
import time


START_DATE = datetime.date(2021, 9, 1)
END_DATE = datetime.date(2026, 9, 1)

OUTPUT_DIR = Path("data/raw_news")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

DAILY_DIR = OUTPUT_DIR / "daily"
DAILY_DIR.mkdir(parents=True, exist_ok=True)


geopolitical_themes = [
    "ARMEDCONFLICT",
    "DIPLOMACY",
    "DIPLOMATIC",
    "MILITARY",
    "REBELLION",
    "TERROR",
    "BORDER",
    "SANCTIONS"
]


def is_geopolitical(themes):
    if pd.isna(themes):
        return False

    theme_set = set(themes.upper().split(";"))

    for theme in geopolitical_themes:
        if theme in theme_set:
            return True

    return False


def count_countries(locations):
    if pd.isna(locations):
        return 0

    countries = set()

    for location in locations.split(";"):
        parts = location.split("#")

        if len(parts) >= 3:
            country_code = parts[2]
            countries.add(country_code)

    return len(countries)


strong_geopolitical_themes = [
    "DIPLOMACY",
    "MILITARY_COOPERATION",
    "ARMEDCONFLICT",
    "BORDER",
    "REBELLION",
    "SANCTIONS",
    "WB_2473_DIPLOMACY_AND_NEGOTIATIONS",
    "WB_2470_PEACE_OPERATIONS_AND_CONFLICT_MANAGEMENT",
    "WB_2432_FRAGILITY_CONFLICT_AND_VIOLENCE",
    "WB_2462_POLITICAL_VIOLENCE_AND_WAR",
    "WB_739_POLITICAL_VIOLENCE_AND_CIVIL_WAR",
    "EPU_CATS_NATIONAL_SECURITY"
]


def has_strong_geopolitical_theme(themes):
    if pd.isna(themes):
        return False

    theme_set = set(themes.upper().split(";"))

    for theme in strong_geopolitical_themes:
        if theme in theme_set:
            return True

    return False


def process_day(current_date):
    date_str = current_date.strftime("%Y%m%d")

    output_file = DAILY_DIR / f"gdelt_{date_str}.csv"

    if output_file.exists():
        print(f"[SKIP] {date_str} already completed")
        return "skipped"

    print()
    print("=" * 60)
    print(f"PROCESSING {date_str}")
    print("=" * 60)

    url = (
        f"https://data.gdeltproject.org/"
        f"gkg/{date_str}.gkg.csv.zip"
    )

    try:
        print("Downloading:", url)

        response = requests.get(
            url,
            timeout=120
        )

        print("Status code:", response.status_code)

        if response.status_code != 200:
            print(f"[FAILED] Could not download {date_str}")
            return "failed"

        with zipfile.ZipFile(
            io.BytesIO(response.content)
        ) as z:

            csv_name = z.namelist()[0]

            with z.open(csv_name) as f:
                df = pd.read_csv(
                    f,
                    sep="\t",
                    low_memory=False
                )

        print("Raw records:", f"{len(df):,}")

        df["IS_GEOPOLITICAL"] = df["THEMES"].apply(
            is_geopolitical
        )

        geopolitical_df = df[
            df["IS_GEOPOLITICAL"]
        ].copy()

        print(
            "Geopolitical records:",
            f"{len(geopolitical_df):,}"
        )

        geopolitical_df["COUNTRY_COUNT"] = (
            geopolitical_df["LOCATIONS"].apply(
                count_countries
            )
        )

        international_df = geopolitical_df[
            geopolitical_df["COUNTRY_COUNT"] >= 2
        ].copy()

        print(
            "International geopolitical records:",
            f"{len(international_df):,}"
        )

        international_df["STRONG_GEOPOLITICAL"] = (
            international_df["THEMES"].apply(
                has_strong_geopolitical_theme
            )
        )

        final_df = international_df[
            international_df["STRONG_GEOPOLITICAL"]
        ].copy()

        print(
            "FINAL records:",
            f"{len(final_df):,}"
        )

        final_df.to_csv(
            output_file,
            index=False
        )

        print()
        print("[SAVED]", output_file)
        print(
            "Records saved:",
            f"{len(final_df):,}"
        )

        del df
        del geopolitical_df
        del international_df
        del final_df

        return "completed"

    except Exception as e:
        print()
        print(f"[ERROR] {date_str}:", e)
        return "failed"


print()
print("=" * 60)
print("GDELT HISTORICAL NEWS COLLECTION")
print("=" * 60)

print("Start date:", START_DATE)
print("End date:", END_DATE)
print("Daily output directory:", DAILY_DIR)
print()


current_date = START_DATE

completed_days = 0
skipped_days = 0
failed_days = 0

while current_date <= END_DATE:

    status = process_day(current_date)

    if status == "completed":
        completed_days += 1

    elif status == "skipped":
        skipped_days += 1

    elif status == "failed":
        failed_days += 1

    current_date += datetime.timedelta(days=1)

    time.sleep(0.5)


print()
print("=" * 60)
print("COMBINING FINAL DATASET")
print("=" * 60)

daily_files = sorted(
    DAILY_DIR.glob("gdelt_*.csv")
)

if daily_files:

    final_output = (
        OUTPUT_DIR /
        "filtered_gdelt_news.csv"
    )

    first_file = True
    total_final_records = 0

    for daily_file in daily_files:

        print("Adding:", daily_file.name)

        daily_df = pd.read_csv(
            daily_file,
            low_memory=False
        )

        total_final_records += len(daily_df)

        daily_df.to_csv(
            final_output,
            mode="w" if first_file else "a",
            header=first_file,
            index=False
        )

        first_file = False

        del daily_df

    print()
    print("FINAL DATASET CREATED:")
    print(final_output)
    print()
    print(
        "Total final records:",
        f"{total_final_records:,}"
    )

else:
    print("No daily datasets found.")


print()
print("=" * 60)
print("COLLECTION COMPLETE")
print("=" * 60)

print("Completed days:", completed_days)
print("Skipped days:", skipped_days)
print("Failed days:", failed_days)

print()
print("Final output:")
print(
    OUTPUT_DIR /
    "filtered_gdelt_news.csv"
)

print("=" * 60)